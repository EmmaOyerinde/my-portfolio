import fs from 'node:fs';
import '../js/evidence-core.js';
import '../js/reliability-core.js';
const reliabilityReports = JSON.parse(fs.readFileSync('data/reliability-reports.json', 'utf8'));
if (!globalThis.EOReliabilityCore.valid(reliabilityReports))
  throw Error('Invalid reviewed reliability reports');
const E = globalThis.EOEvidence,
  manifest = JSON.parse(fs.readFileSync('data/source-status.json', 'utf8')),
  datasets = {};
for (const kind of E.kinds.filter((k) => k !== 'boundaries')) {
  const d = JSON.parse(fs.readFileSync('data/' + E.files[kind], 'utf8'));
  if (!E.valid(kind, d)) throw Error('Invalid seed ' + kind);
  datasets[kind] = d;
}
const seed = { manifest, datasets };
const references = {
  reliabilityReports,
  customerReferences: JSON.parse(fs.readFileSync('data/customer-references.json', 'utf8')).counts,
  customerReports: JSON.parse(fs.readFileSync('data/customer-reports.json', 'utf8')).reports,
  mapping: JSON.parse(fs.readFileSync('data/reliability-mapping.json', 'utf8')),
};
fs.writeFileSync(
  'js/evidence-seed.js',
  '/* Dated, validated publications for immediate and offline fallback rendering. Generated by scripts/prepare-seed.mjs. */\nwindow.EOEvidenceSeed=' +
    JSON.stringify(seed)
      .replace(/</g, '\\u003c')
      .replace(/\u2028/g, '\\u2028')
      .replace(/\u2029/g, '\\u2029') +
    ';\n',
);
// Reviewed reports and reference counts are independent of refreshed observations.
fs.writeFileSync(
  'js/reference-data.js',
  '/* Reviewed report excerpts, reference estimates and utility mapping. Generated by scripts/prepare-seed.mjs. */\nwindow.EOReferenceData=' +
    JSON.stringify(references).replace(/</g, '\\u003c') +
    ';\n',
);
